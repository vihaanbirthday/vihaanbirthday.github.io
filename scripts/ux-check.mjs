import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { openChapter } from './browser-helpers.mjs';
const base = process.env.TEST_URL || 'http://127.0.0.1:4173';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
try {
 const page = await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 async function openGame(name) {
  await page.locator(`button[data-game="${name}"]`).click();
  await page.locator('.game-loading').waitFor({state:'detached'});
  return page.frames().find(frame=>frame.url().includes(`/games/${name}/`));
 }
 await page.goto(base);
 await openChapter(page,'#venue');
 await page.locator('.gaming-shortcut').click();
 let frame=await openGame('hextris');
 assert.equal(await frame.locator('#startBtn').evaluate(el=>el.tagName),'BUTTON');
 await frame.locator('#startBtn').press('Enter');
 await frame.waitForFunction(()=>gameState===1);
 await frame.locator('#pauseBtn').press('Space');
 await frame.waitForFunction(()=>gameState===-1);
 await frame.waitForFunction(()=>pausable);
 assert.equal(await frame.locator('#pauseBtn').getAttribute('aria-label'),'Resume game');
 await frame.locator('#pauseBtn').press('Enter');
 await frame.waitForFunction(()=>gameState===1);
 await page.locator('#close-game').click();
 await page.locator('#game-exit-dialog').waitFor({state:'visible'});
 await page.locator('#keep-playing').click();
 assert(await page.locator('#game-dialog').isVisible());
 assert.equal(page.frames().find(f=>f.url().includes('/hextris/')),frame,'Cancelling an exit retains the original game frame');
 // Browser Back must restore the current chapter until the guest decides.
 await page.goBack();
 await page.locator('#game-exit-dialog').waitFor({state:'visible'});
 await page.waitForURL('**/#games');
 await page.locator('#keep-playing').click();
 assert(await page.locator('#game-dialog').isVisible());
 await page.goBack();
 await page.locator('#game-exit-dialog').waitFor({state:'visible'});
 await page.locator('#discard-game').click();
 await page.waitForFunction(()=>document.body.dataset.page==='venue' && !document.querySelector('iframe'));
 await page.locator('.gaming-shortcut').click();
 frame=await openGame('ohhi');
 assert(await frame.locator('#menu').isVisible(),'Puzzle choices appear when loading completes');
 await frame.locator('#menu [data-action="play"]').press('Enter');
 await frame.locator('[data-size="1"]').press('Space');
 await frame.locator('#board:not(.hidden) button').first().waitFor({state:'visible'});
 const tileId=await frame.locator('#board .tile:not(.tile-1):not(.tile-2)').first().getAttribute('id');
 const tile=frame.locator(`#${tileId} button`);
 const before=await tile.getAttribute('aria-label');
 await tile.press('Space');
 assert.notEqual(await tile.getAttribute('aria-label'),before,'Keyboard activation changes the puzzle tile and its accessible label');
 await tile.press('ArrowDown');
 assert.notEqual(await frame.evaluate(()=>document.activeElement.parentElement.id),tileId,'Arrow keys move between puzzle tiles');
 assert.equal(await frame.locator('#board button[tabindex="0"]').count(),1,'The board uses a single keyboard entry point');
 await page.locator('#restart-game').click();
 await page.locator('#game-exit-dialog').waitFor({state:'visible'});
 assert.equal(await page.locator('#game-exit-title').textContent(),'Restart this game?');
 await page.locator('#discard-game').click();
 await page.locator('.game-loading').waitFor({state:'detached'});
 await page.locator('#close-game').click();
 await page.locator('#game-dialog').waitFor({state:'hidden'});
 // Deterministic clock checks that a pause freezes both physics and difficulty.
 frame=await openGame('flappy');
 await page.clock.install();await page.clock.pauseAt(new Date());
 await frame.locator('[data-character="pip"]').click();
 await frame.locator('#start-flight').click();await frame.locator('#demo-start').click();
 await page.clock.runFor(80);
 await frame.locator('#pause-flight').click();
 const pose=()=>frame.evaluate(()=>({position,velocity,score,towerElapsedMs}));
 const paused=await pose();assert.equal(await frame.evaluate(()=>currentstate),4);
 await page.clock.runFor(3000);assert.deepEqual(await pose(),paused,'Pausing freezes the flight');
 await frame.locator('#resume-flight').press('Enter');
 await page.clock.runFor(32);assert.notDeepEqual(await pose(),paused,'Resuming advances the same flight');
 await frame.evaluate(()=>{Object.defineProperty(document,'hidden',{value:true,configurable:true});document.dispatchEvent(new Event('visibilitychange'));});
 assert.equal(await frame.evaluate(()=>currentstate),4,'A hidden page automatically pauses flight');
 const hiddenPose=await pose();await page.clock.runFor(1000);assert.deepEqual(await pose(),hiddenPose);
 await frame.evaluate(()=>{delete document.hidden;});
 await page.locator('#close-game').click();await page.locator('#game-exit-dialog').waitFor({state:'visible'});
 await page.locator('#keep-playing').click();assert.deepEqual(await pose(),hiddenPose,'Declining to leave preserves the paused flight');
 await page.locator('.game-tabs a[href="#rsvp"]').click();await page.locator('#game-exit-dialog').waitFor({state:'visible'});
 await page.locator('#discard-game').click();
 assert.equal(new URL(page.url()).hash,'#rsvp');
 await page.waitForFunction(()=>!document.querySelector('iframe'));
 assert.deepEqual(errors,[]);
 console.log('Immediate puzzle menu, keyboard controls, guarded close/restart/navigation/browser Back, cancelled exits, and flight pause/resume/visibility passed.');
} finally { await browser.close(); }
